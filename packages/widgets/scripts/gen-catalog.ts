/**
 * Generates packages/widgets/src/catalog.ts: the widget catalogue the AI layer reads (ids, what each
 * widget is for, what the learner does, what it reports, JSON Schemas for props/goal/answer, and
 * one worked example). Pure data, no React and no tokenizer, so prompts can import it cheaply.
 *
 *   bun packages/widgets/scripts/gen-catalog.ts          # write src/catalog.ts
 *   bun packages/widgets/scripts/gen-catalog.ts --check  # exit 1 if it is stale
 */
import { WIDGET_IDS, type WidgetId, type WidgetSpec } from "@learncroc/core";
import { z } from "zod";
import { WIDGET_SPECS } from "../src/spec";

export interface CatalogEntry {
  id: WidgetId;
  title: string;
  family: WidgetSpec<unknown, unknown, unknown>["family"];
  description: string;
  llmDoc: WidgetSpec<unknown, unknown, unknown>["llmDoc"];
  props: unknown;
  goal: unknown | null;
  answer: unknown;
  example: { note: string; props: unknown; goal: unknown; correctAnswer: unknown } | null;
}

function schema(t: z.ZodType): unknown {
  const s = z.toJSONSchema(t, { io: "input", unrepresentable: "any" }) as Record<string, unknown>;
  const { $schema: _drop, ...rest } = s;
  return rest;
}

export function buildCatalog(): CatalogEntry[] {
  return WIDGET_IDS.map((id) => {
    const spec = WIDGET_SPECS[id] as WidgetSpec<unknown, unknown, unknown>;
    const ex = spec.examples[0];
    return {
      id,
      title: spec.title,
      family: spec.family,
      description: spec.description,
      llmDoc: spec.llmDoc,
      props: schema(spec.props as z.ZodType),
      goal: spec.goal ? schema(spec.goal as z.ZodType) : null,
      answer: schema(spec.answer as z.ZodType),
      example: ex ? { note: ex.note, props: ex.props, goal: ex.goal, correctAnswer: ex.correctAnswer } : null,
    };
  });
}

export function renderCatalog(entries: CatalogEntry[]): string {
  return `/**
 * GENERATED by packages/widgets/scripts/gen-catalog.ts from the widget specs. Do not edit by hand:
 * run \`bun packages/widgets/scripts/gen-catalog.ts\`.
 *
 * The widget catalogue for the AI layer: pure data (no React, no tokenizer), safe to import anywhere.
 */
import type { WidgetId } from "@learncroc/core";

export interface WidgetCatalogEntry {
  id: WidgetId;
  title: string;
  family: "llm" | "generic" | "physics" | "language" | "code";
  description: string;
  llmDoc: { useWhen: string; notFor: string; learnerDoes: string; reports: string };
  /** JSON Schema (draft 2020-12) of the props. */
  props: unknown;
  /** JSON Schema of the goal, or null for explore-only widgets. */
  goal: unknown | null;
  /** JSON Schema of the answer the widget reports. */
  answer: unknown;
  /** One worked example (props, goal and an answer that grades correct). */
  example: { note: string; props: unknown; goal: unknown; correctAnswer: unknown } | null;
}

// biome-ignore format: generated data
export const WIDGET_CATALOG: readonly WidgetCatalogEntry[] = ${JSON.stringify(entries, null, 2)};

/** One entry by id. */
export function catalogEntry(id: WidgetId): WidgetCatalogEntry | undefined {
  return WIDGET_CATALOG.find((e) => e.id === id);
}

/**
 * A compact text block describing widgets for a prompt: what each is for, what the learner does,
 * what it reports, and its example. Pass ids to limit it; schemas are included when asked.
 */
export function widgetCatalogText(opts: { ids?: readonly WidgetId[]; schemas?: boolean } = {}): string {
  const list = opts.ids ? WIDGET_CATALOG.filter((e) => opts.ids?.includes(e.id)) : WIDGET_CATALOG;
  return list
    .map((e) => {
      const lines = [
        \`## \${e.id} (\${e.family}): \${e.title}\`,
        e.description,
        \`Use when: \${e.llmDoc.useWhen}\`,
        \`Not for: \${e.llmDoc.notFor}\`,
        \`Learner does: \${e.llmDoc.learnerDoes}\`,
        \`Reports: \${e.llmDoc.reports}\`,
      ];
      if (e.example)
        lines.push(\`Example (\${e.example.note}): \${JSON.stringify({ props: e.example.props, goal: e.example.goal })}\`);
      if (opts.schemas)
        lines.push(\`Props schema: \${JSON.stringify(e.props)}\`, \`Goal schema: \${JSON.stringify(e.goal)}\`);
      return lines.join("\\n");
    })
    .join("\\n\\n");
}
`;
}

if (import.meta.main) {
  const path = new URL("../src/catalog.ts", import.meta.url).pathname;
  const next = renderCatalog(buildCatalog());
  const current = await Bun.file(path)
    .text()
    .catch(() => "");
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error("src/catalog.ts is stale: run bun packages/widgets/scripts/gen-catalog.ts");
      process.exit(1);
    }
    console.log("catalog.ts is up to date");
  } else {
    await Bun.write(path, next);
    console.log(`wrote ${path} (${WIDGET_IDS.length} widgets)`);
  }
}
