import { describe, expect, test } from "bun:test";
import {
  canonicalJson,
  cardWords,
  compilePack,
  contentHashOf,
  generateFlashcards,
  layoutMap,
  sha256Hex,
} from "../src/index";
import { cleanFiles, editYaml, type Files, fixtureFiles, fixturePack, fsOf } from "./support/pack";

const AT = "2026-10-20T00:00:00Z";

async function compileFiles(files: Files, opts = {}) {
  return compilePack(fsOf(files), { at: AT, ...opts });
}

describe("compile", () => {
  test("the mini-pack sources compile to exactly the committed pack.json", async () => {
    const { pack, issues } = await compileFiles(fixtureFiles());
    expect(issues.filter((i) => i.severity === "error")).toEqual([]);
    if (!pack) throw new Error("no pack");
    // pack.json is generated by compileSources; regenerate it after editing the fixture YAML.
    expect(pack).toEqual(fixturePack());
    expect(pack.format).toBe(2);
    expect(pack.compiledWith).toEqual({ learncroc: "0.1.0", at: AT });
    expect(pack.contentHash).toBe(await contentHashOf(pack as unknown as Record<string, unknown>));
  });

  test("checkpoints: covers, size, title, minutes and the gate on covered cards; stats", async () => {
    const { pack } = await compileFiles(fixtureFiles());
    if (!pack) throw new Error("no pack");
    expect(pack.map.nodes["checkpoint-basics"]).toMatchObject({
      kind: "checkpoint",
      title: "Check 1",
      teaser: "",
      covers: ["units", "unit-conversion"],
      size: 3,
      estMinutes: 3,
    });
    expect(pack.map.nodes["checkpoint-trip"]).toMatchObject({ title: "The Trip", covers: ["speed"], size: 3 });
    expect(pack.map.nodes["unit-conversion"]?.gate).toBe("checkpoint-basics");
    expect(pack.map.nodes["average-speed"]).toMatchObject({ status: "planned", title: "Average speed" });
    expect(pack.map.nodes["average-speed"]?.gate).toBeUndefined();
    expect(pack.nodes["checkpoint-basics"]).toBeUndefined();
    const words = Object.values(pack.nodes).reduce((t, n) => t + cardWords(n, "en").total, 0);
    expect(pack.stats).toEqual({
      nodes: 6,
      playable: 5,
      planned: 1,
      checkpoints: 2,
      screens: 9,
      items: 18,
      flashcards: 6,
      words,
    });
    // An explicit size and gateName-based default titles.
    const sized = editYaml<{ nodes: Record<string, Record<string, unknown>> }>(fixtureFiles(), "map.yaml", (m) => {
      (m.nodes["checkpoint-basics"] as Record<string, unknown>).size = 5;
    });
    const r = await compileFiles(
      editYaml<{ theme: Record<string, unknown> }>(sized, "pack.yaml", (m) => {
        m.theme.gateName = "Power check";
      }),
    );
    expect(r.pack?.map.nodes["checkpoint-basics"]).toMatchObject({ size: 5, estMinutes: 4, title: "Power check 1" });
  });

  test("layout and hash are deterministic", async () => {
    const a = await compileFiles(fixtureFiles());
    const b = await compileFiles(fixtureFiles());
    expect(canonicalJson(a.pack)).toBe(canonicalJson(b.pack));
    expect(a.pack?.contentHash).toBe(b.pack?.contentHash as string);
    const c = await compileFiles(fixtureFiles(), { at: "2026-10-21T00:00:00Z" });
    expect(c.pack?.contentHash).not.toBe(a.pack?.contentHash as string);
    expect(c.pack?.map.layout).toEqual(a.pack?.map.layout as NonNullable<typeof a.pack>["map"]["layout"]);
  });

  test("grid snap, direction and pins", async () => {
    const nodes = [
      { id: "a", requires: [], line: "x" },
      { id: "b", requires: ["a"], line: "x" },
      { id: "c", requires: ["a"], line: "y" },
      { id: "d", requires: ["b", "c"], line: "x" },
    ].map((n) => ({ ...n, kind: "node" as const, status: "playable" as const, title: n.id, teaser: "" }));
    const lines = [
      { id: "x", title: "X", color: 1 as const, outcome: "" },
      { id: "y", title: "Y", color: 2 as const, outcome: "" },
    ];
    const lr = await layoutMap({ nodes, lines, direction: "lr" });
    for (const p of Object.values(lr.nodes)) {
      expect((p.x - 84) % 168).toBe(0);
      expect((p.y - 56) % 112).toBe(0);
    }
    expect(lr.nodes.a?.col).toBe(0);
    expect(lr.nodes.d?.col).toBe(2);
    expect(lr.nodes.b?.row).toBe(lr.nodes.a?.row as number);
    expect(lr.edges.find((e) => e.from === "a" && e.to === "c")?.kind).toBe("interchange");
    expect(lr.lines).toEqual({ x: ["a", "b", "d"], y: ["c"] });
    const bt = await layoutMap({ nodes, lines, direction: "bt" });
    expect(bt.direction).toBe("bt");
    expect(bt.nodes.a?.row).toBeGreaterThan(bt.nodes.d?.row as number);
    expect(bt.width).toBe(lr.height * (168 / 112));
    const pinned = await layoutMap({ nodes, lines, direction: "lr", pins: { c: { col: 1, row: 3 } } });
    expect(pinned.nodes.c).toMatchObject({ col: 1, row: 3 });
    expect(await layoutMap({ nodes: [], lines, direction: "lr" })).toMatchObject({ width: 0, height: 0, edges: [] });
  });

  test("$data inlining, generated flashcards, suggested start default", async () => {
    let files = cleanFiles();
    files["data/numbers.json"] = JSON.stringify({ prompts: { speed: "How fast is walking, in km/h?" } });
    files = editYaml<{ items: Record<string, unknown>[] }>(files, "nodes/speed.yaml", (n) => {
      const i4 = n.items.find((i) => i.id === "i4");
      if (i4) i4.prompt = { $data: "data/numbers.json#/prompts/speed" };
    });
    files = editYaml<{ entry: Record<string, unknown> }>(files, "pack.yaml", (m) => {
      delete m.entry.suggestedStart;
    });
    const { pack } = await compileFiles(files);
    expect(pack?.nodes.speed?.items.find((i) => i.id === "i4")?.prompt).toBe("How fast is walking, in km/h?");
    expect(pack?.manifest.entry.suggestedStart).toBe("units");
    const node = pack?.nodes["unit-conversion"];
    expect(node?.flashcards?.length).toBeGreaterThan(0);
    expect(generateFlashcards(node as NonNullable<typeof node>).length).toBeLessThanOrEqual(3);
  });

  test("audio sources come from the packs:audio manifest", async () => {
    let files = cleanFiles();
    files = editYaml<{ screens: { blocks: Record<string, unknown>[] }[] }>(files, "nodes/units.yaml", (n) => {
      n.screens[1]?.blocks.push({ type: "audio", tts: { text: "Dos  horas", lang: "es-ES" }, transcript: "Dos horas" });
    });
    files["data/audio-manifest.json"] = JSON.stringify({
      schema: 1,
      generator: "t",
      voices: {},
      phrases: { "es-ES|Dos horas": { src: "assets/audio/es-es-0123456789abcdef.ogg", bytes: 10 } },
    });
    const { pack } = await compileFiles(files);
    const block = pack?.nodes.units?.screens[1]?.blocks.find((b) => b.type === "audio");
    expect(block && block.type === "audio" && block.src).toBe("assets/audio/es-es-0123456789abcdef.ogg");
  });

  test("building cards: no file needed, provisional hash", async () => {
    const files = fixtureFiles();
    delete files["nodes/speed.yaml"];
    const broken = await compileFiles(files);
    expect(broken.pack).toBeUndefined();
    expect(broken.issues.some((i) => /no nodes\/speed\.yaml/.test(i.message))).toBe(true);
    const { pack, issues } = await compileFiles(files, { building: ["speed"] });
    expect(issues.filter((i) => i.severity === "error")).toEqual([]);
    expect(pack?.provisional).toBe(true);
    expect(pack?.map.nodes.speed?.status).toBe("building");
    expect(pack?.nodes.speed).toBeUndefined();
  });

  test("errors: cycles, unknown requirements, id mismatches, bad $data, schema problems", async () => {
    const cyc = editYaml<{ nodes: Record<string, { requires: string[] }> }>(fixtureFiles(), "map.yaml", (m) => {
      (m.nodes.units as { requires: string[] }).requires = ["unit-conversion"];
    });
    expect((await compileFiles(cyc)).issues.some((i) => /cycle/.test(i.message))).toBe(true);
    const unknown = editYaml<{ nodes: Record<string, { requires: string[] }> }>(fixtureFiles(), "map.yaml", (m) => {
      (m.nodes.speed as { requires: string[] }).requires = ["ghost"];
    });
    expect((await compileFiles(unknown)).issues.some((i) => /unknown entry "ghost"/.test(i.message))).toBe(true);
    const mismatch = editYaml<{ id: string }>(fixtureFiles(), "nodes/units.yaml", (n) => {
      n.id = "unitz";
    });
    expect((await compileFiles(mismatch)).issues.some((i) => /doesn't match the file name/.test(i.message))).toBe(true);
    const data = editYaml<{ close: { text: unknown } }>(fixtureFiles(), "nodes/units.yaml", (n) => {
      n.close.text = { $data: "data/../secret.json" };
    });
    expect((await compileFiles(data)).issues.some((i) => /\$data must look like/.test(i.message))).toBe(true);
    const schema = editYaml<{ estMinutes: unknown }>(fixtureFiles(), "nodes/units.yaml", (n) => {
      n.estMinutes = "soon";
    });
    const r = await compileFiles(schema);
    expect(r.pack).toBeUndefined();
    expect(r.issues.find((i) => i.file === "nodes/units.yaml")).toMatchObject({ path: "/estMinutes" });
    expect(r.issues.find((i) => i.file === "nodes/units.yaml")?.line).toBeGreaterThan(1);
  });

  test("revision-2 leftovers: bosses/, toy.yaml, format 1, a node file for a checkpoint", async () => {
    const bosses = { ...fixtureFiles(), "bosses/boss-trip.yaml": "id: boss-trip\n" };
    const b = await compileFiles(bosses);
    expect(b.pack).toBeUndefined();
    expect(b.issues.some((i) => /bosses\/ and toy\.yaml were removed/.test(i.message))).toBe(true);
    const toy = await compileFiles({ ...fixtureFiles(), "toy.yaml": "kind: trace-run\n" });
    expect(toy.issues.some((i) => i.file === "toy.yaml" && /run `learncroc migrate`/.test(i.message))).toBe(true);
    const old = editYaml<{ schema: number }>(fixtureFiles(), "pack.yaml", (m) => {
      m.schema = 1;
    });
    const o = await compileFiles(old);
    expect(o.issues.filter((i) => i.file === "pack.yaml").map((i) => i.message)).toEqual([
      "pack format 1: run `learncroc migrate`",
    ]);
    const files = fixtureFiles();
    const cp = await compileFiles({
      ...files,
      "nodes/checkpoint-basics.yaml": String(files["nodes/units.yaml"]).replace("id: units", "id: checkpoint-basics"),
    });
    expect(cp.issues.some((i) => /checkpoints have no node file/.test(i.message))).toBe(true);
  });

  test("sha256 is the standard digest", async () => {
    expect(await sha256Hex("abc")).toBe("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
    expect(canonicalJson({ b: 1, a: [{ d: 1, c: undefined }] })).toBe('{"a":[{"d":1}],"b":1}');
  });
});
