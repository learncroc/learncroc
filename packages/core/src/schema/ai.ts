/**
 * AI layer data shapes. Provider interfaces (AIProvider, TextRequest) live in
 * packages/ai because they carry functions; everything serialisable is here.
 */
import { z } from "zod";
import { AnswerValue, HtmlGoal, Item } from "./interactions";
import { Misconception, PackNode } from "./node";
import { Hex, NodeId, RendererId } from "./primitives";

export const SystemBlock = z.object({ text: z.string(), cache: z.enum(["5m", "1h"]).optional() });
export const ChatTurn = z.object({ role: z.enum(["user", "assistant"]), content: z.string() });

/** Create pipeline: the streamed pocket-map skeleton (structured output). */
export const MinimapSkeleton = z.object({
  title: z.string(),
  /** ≤ 25 words. */
  gist: z.string(),
  renderer: RendererId,
  /** 5 suggestions; corrected by theme lint. */
  palette: z.array(Hex).optional(),
  /** Reading order. Sections are not generated by the model: code computes them (sectionSizes). */
  nodes: z.array(
    z.object({
      id: NodeId,
      /** ≤ 4 words. */
      title: z.string(),
      landmark: z.string().optional(),
      objective: z.string(),
      /** 2–3. */
      keyPoints: z.array(z.string()),
      /** ["p3","p4"] */
      paras: z.array(z.string()),
      hookIdea: z.string(),
      hookStyle: z.enum(["puzzle", "surprise", "what-would-you-do"]).optional(),
      /** 1–2. */
      misconceptions: z.array(z.object({ id: z.string(), label: z.string() })),
      caution: z.string().nullable(),
      requires: z.array(NodeId),
    }),
  ),
  edges: z.array(z.object({ from: NodeId, to: NodeId })),
});

/** `pocket` profile: hook, 2–3 beats, close + teaser, ≥ 6 items (≥ 3 transfer), 3 flashcards, 1–2 misconceptions. */
export const NodeFill = PackNode.omit({
  status: true,
  provenance: true,
  grounding: true,
  renamedFrom: true,
  underTheHood: true,
  toy: true,
});

/** Illustration contract; DOMPurify-stable or dropped. */
export const GeneratedFigure = z.object({ nodeId: NodeId, screenId: z.string(), svg: z.string(), alt: z.string() });
/** Parked. ≤ 64 KB; must pass ready + selftest. */
export const GeneratedToy = z.object({
  nodeId: NodeId,
  html: z.string(),
  alt: z.string(),
  height: z.number(),
  goal: HtmlGoal.optional(),
});

export const QuizVariantRequest = z.object({
  item: Item,
  keyPoints: z.array(z.string()),
  misconceptions: z.record(z.string(), Misconception),
});
export const SolverResult = z.object({ answer: AnswerValue, agrees: z.boolean() });

export type SystemBlock = z.infer<typeof SystemBlock>;
export type ChatTurn = z.infer<typeof ChatTurn>;
export type MinimapSkeleton = z.infer<typeof MinimapSkeleton>;
export type NodeFill = z.infer<typeof NodeFill>;
export type GeneratedFigure = z.infer<typeof GeneratedFigure>;
export type GeneratedToy = z.infer<typeof GeneratedToy>;
export type QuizVariantRequest = z.infer<typeof QuizVariantRequest>;
export type SolverResult = z.infer<typeof SolverResult>;
